import { toPacDirective } from './proxy-parser.js';

/**
 * Генерирует PAC-скрипт для точечной маршрутизации доменов Google AI.
 *
 * Почему без DIRECT в конце цепочки для Gemini:
 * если прокси временно недоступен, молчаливый откат на DIRECT отправит запрос
 * с российского IP, Google выдаст геоблок и может запомнить отказ в сессии.
 * Весь остальной трафик браузера всегда уходит DIRECT без лишних DNS-вызовов.
 *
 * probeOverride (опционально): { host: '1.0.0.1', proxy: {...} } —
 * направляет ОДИН служебный хост через проверяемый кандидат-прокси,
 * не прерывая работу активного маршрута для Gemini.
 */
export function buildPacScript({ domains, proxies, probeOverride = null }) {
  const cleanDomains = Array.from(
    new Set((domains || []).map((d) => String(d).trim().toLowerCase()).filter(Boolean))
  );
  const directives = (proxies || []).map(toPacDirective);
  const proxyChain = directives.join('; ');

  const probeHost = probeOverride?.host ? String(probeOverride.host).toLowerCase() : '';
  const probeDirective = probeOverride?.proxy ? toPacDirective(probeOverride.proxy) : '';

  const domainsJson = JSON.stringify(cleanDomains);
  const chainJson = JSON.stringify(proxyChain);
  const probeHostJson = JSON.stringify(probeHost);
  const probeDirJson = JSON.stringify(probeDirective);

  // Chromium chrome.proxy.settings.set требует строго ASCII в pacScript.data.
  return `// Generated by NZ Chrome extension
var AI_DOMAINS = ${domainsJson};
var AI_PROXY_CHAIN = ${chainJson};
var PROBE_HOST = ${probeHostJson};
var PROBE_DIRECTIVE = ${probeDirJson};

function matchesDomain(host, rule) {
  if (rule.charAt(0) === "=") {
    return host === rule.slice(1);
  }
  if (host === rule) return true;
  var suffix = "." + rule;
  return host.length > suffix.length && host.indexOf(suffix, host.length - suffix.length) !== -1;
}

function FindProxyForURL(url, host) {
  if (!host) return "DIRECT";
  var h = host.toLowerCase();

  if (PROBE_HOST && PROBE_DIRECTIVE && h === PROBE_HOST) {
    return PROBE_DIRECTIVE;
  }

  if (!AI_PROXY_CHAIN) {
    return "DIRECT";
  }

  for (var i = 0; i < AI_DOMAINS.length; i++) {
    if (matchesDomain(h, AI_DOMAINS[i])) {
      return AI_PROXY_CHAIN;
    }
  }

  return "DIRECT";
}
`;
}
